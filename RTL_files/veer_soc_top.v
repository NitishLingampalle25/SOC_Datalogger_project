// =============================================================================
// Module  : veer_soc_top
// File    : RTL_files/veer_soc_top.v
//
// Purpose : Full-system integration model for simulation.
//           Wraps veer_wrapper_uart_integrated and adds:
//             1. IMEM  – 64-bit AXI4 instruction memory slave
//                        Loaded from hex file via $readmemh
//                        Responds to IFU AXI read requests at 0x8000_0000
//             2. Tie-offs for all unused top-level ports:
//                SB (debug system bus), DMA slave, JTAG, scan, etc.
//             3. tohost monitor – watches writes to 0xD058_0000 and
//                prints PASS / FAIL based on the written value
//
// Memory map:
//   0x8000_0000 – 0x8000_FFFF   IMEM  (64 KB, 8192 x 64-bit words)
//   0x4000_0000 – 0x4000_001F   UART  (via interconnect inside DUT)
//   0xD058_0000                 tohost / simulation exit register
//
// Parameters:
//   IMEM_FILE   – path to hex file produced by uart_rw_test build
//   CLK_PERIOD  – system clock half-period in ns (default 5 → 100 MHz)
//
// Usage (compile together with runf.f):
//   vcs -full64 -sverilog -debug_access+all -kdb \
//       +define+RV_BUILD_AXI4 +define+RV_PHYSICAL \
//       -f run/runf.f \
//       RTL_files/veer_soc_top.v \
//       +define+IMEM_FILE=\"uart_rw_test.hex\" \
//       -o simv_soc
//   ./simv_soc +fsdb+delta -l sim_soc.log
// =============================================================================

