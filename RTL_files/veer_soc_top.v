    // Waveform dump
    // =========================================================================
    initial begin
        $fsdbDumpfile("veer_soc_top.fsdb");
        $fsdbDumpvars(0, veer_soc_top);
        $dumpfile("veer_soc_top.vcd");
        $dumpvars(0, veer_soc_top);
        $display("[SIM] Starting veer_soc_top full-system simulation");
        $display("[SIM] Clock period = %0d ns, Reset cycles = %0d", CLK_PERIOD*2, RST_CYCLES);
    end

