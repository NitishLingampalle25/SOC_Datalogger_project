    // =========================================================================
    // IMEM – AXI4 instruction memory slave (64-bit data, single-beat)
    // Base address: 0x8000_0000  Size: 64 KB = 8192 x 64-bit words
    //
    // Protocol:
    //   - Accepts AR channel when address is in IMEM range
    //   - Returns rdata one cycle after AR handshake (zero-latency RAM model)
    //   - Supports arlen > 0 (burst) by incrementing address each beat
    //   - arsize=3 (8 bytes) expected from IFU – returns full 64-bit word
    // =========================================================================
    reg [63:0] imem [0:IMEM_DEPTH-1];

    // Load hex file at time 0
    initial begin
        integer i;
        for (i = 0; i < IMEM_DEPTH; i = i + 1)
            imem[i] = 64'h0000_0000_0000_0013; // default: NOP (ADDI x0,x0,0)
        $readmemh(IMEM_FILE, imem);
        $display("[IMEM] Loaded '%s' into instruction memory (%0d x 64-bit words)",
                 IMEM_FILE, IMEM_DEPTH);
    end

    // IMEM AXI state machine
    reg  [1:0]             imem_state;
    localparam IMEM_IDLE   = 2'd0;
    localparam IMEM_RDATA  = 2'd1;

    reg  [IFU_BUS_TAG-1:0] imem_rid_r;
    reg  [31:0]            imem_araddr_r;
    reg  [7:0]             imem_arlen_r;
    reg  [7:0]             imem_beat_r;    // current beat count
    reg                    imem_arready_r;
    reg                    imem_rvalid_r;
    reg  [63:0]            imem_rdata_r;
    reg                    imem_rlast_r;

    assign ifu_axi_arready = imem_arready_r;
    assign ifu_axi_rvalid  = imem_rvalid_r;
    assign ifu_axi_rid     = imem_rid_r;
    assign ifu_axi_rdata   = imem_rdata_r;
    assign ifu_axi_rresp   = 2'b00;
    assign ifu_axi_rlast   = imem_rlast_r;

    always @(posedge clk or negedge rst_l) begin
        if (!rst_l) begin
            imem_state    <= IMEM_IDLE;
            imem_arready_r<= 1'b1;
            imem_rvalid_r <= 1'b0;
            imem_rlast_r  <= 1'b0;
            imem_beat_r   <= 8'h0;
            imem_rdata_r  <= 64'h0;
            imem_rid_r    <= {IFU_BUS_TAG{1'b0}};
            imem_araddr_r <= 32'h0;
            imem_arlen_r  <= 8'h0;
        end else begin
            case (imem_state)
                IMEM_IDLE: begin
                    imem_rvalid_r <= 1'b0;
                    imem_arready_r<= 1'b1;
                    if (ifu_axi_arvalid && imem_arready_r) begin
                        imem_arready_r <= 1'b0;
                        imem_rid_r     <= ifu_axi_arid;
                        imem_araddr_r  <= ifu_axi_araddr;
                        imem_arlen_r   <= ifu_axi_arlen;
                        imem_beat_r    <= 8'h0;
                        imem_state     <= IMEM_RDATA;
                        // Present first beat immediately next cycle
                        imem_rvalid_r  <= 1'b1;
                        imem_rdata_r   <= imem[(ifu_axi_araddr - IMEM_BASE) >> 3];
                        imem_rlast_r   <= (ifu_axi_arlen == 8'h0);
                    end
                end
                IMEM_RDATA: begin
                    if (imem_rvalid_r && ifu_axi_rready) begin
                        if (imem_rlast_r) begin
                            // Last beat accepted
                            imem_rvalid_r  <= 1'b0;
                            imem_rlast_r   <= 1'b0;
                            imem_arready_r <= 1'b1;
                            imem_state     <= IMEM_IDLE;
                        end else begin
                            // Advance to next beat
                            imem_beat_r   <= imem_beat_r + 8'h1;
                            imem_araddr_r <= imem_araddr_r + 32'h8;
                            imem_rdata_r  <= imem[(imem_araddr_r + 32'h8 - IMEM_BASE) >> 3];
                            imem_rlast_r  <= (imem_beat_r + 8'h1 == imem_arlen_r);
                        end
                    end
                end
                default: imem_state <= IMEM_IDLE;
            endcase
        end
    end

    // =========================================================================
    // tohost monitor
    // Watches the LSU AXI write channel inside the DUT for writes to TOHOST.
    // We tap the internal lsu_axi_*_w wires via hierarchical reference.
    // =========================================================================
    wire        lsu_aw_hs = dut.u_dwidth_conv.m_axi_awvalid &&
                            dut.u_dwidth_conv.m_axi_awready;
    wire        lsu_w_hs  = dut.u_dwidth_conv.m_axi_wvalid  &&
                            dut.u_dwidth_conv.m_axi_wready;

    reg  [31:0] lsu_awaddr_lat;
    reg         lsu_aw_pend;

    always @(posedge clk or negedge rst_l) begin
        if (!rst_l) begin
            lsu_awaddr_lat <= 32'h0;
            lsu_aw_pend    <= 1'b0;
        end else begin
            if (lsu_aw_hs) begin
                lsu_awaddr_lat <= dut.u_dwidth_conv.m_axi_awaddr;
                lsu_aw_pend    <= 1'b1;
            end
            if (lsu_w_hs && lsu_aw_pend) begin
                lsu_aw_pend <= 1'b0;
                if (lsu_awaddr_lat == TOHOST_ADDR) begin
                    $display("\n[TOHOST @ %0t ns] write = 0x%08h", $time,
                             dut.u_dwidth_conv.m_axi_wdata[31:0]);
                    if (dut.u_dwidth_conv.m_axi_wdata[31:0] == 32'hDEAD_BEEF) begin
                        $display(">>> [PASS] uart_rw_test: ALL TESTS PASSED <<<\n");
                    end else begin
                        $display(">>> [FAIL] uart_rw_test: FAIL CODE = 0x%08h <<<\n",
                                 dut.u_dwidth_conv.m_axi_wdata[31:0]);
                    end
                    $finish;
                end
            end
        end
    end

    // =========================================================================
    // UART TX monitor – print each transmitted byte
    // =========================================================================
    reg uart_tx_prev = 1'b1;
    always @(posedge clk) begin
        uart_tx_prev <= uart_tx_o;
        if (uart_tx_prev && !uart_tx_o)
            $display("[UART-TX @ %0t ns] start-bit detected on uart_tx_o", $time);
    end

    // =========================================================================
    // Simulation timeout watchdog (50 ms @ 100 MHz = 5,000,000 cycles)
    // =========================================================================
    initial begin
        #(5_000_000 * CLK_PERIOD * 2);
        $display("[TIMEOUT] Simulation exceeded limit – no tohost write detected");
        $finish;
    end

